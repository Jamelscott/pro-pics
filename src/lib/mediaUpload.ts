import { randomUUID } from "expo-crypto";
import { createMediaMany } from "./media";
import { getCurrentUserId, removeFromBucket, uploadToBucket } from "./storage";

interface UploadAndCreateParams {
  uri: string;
  projectId: string;
  folderId?: string | null;
  mimeType: string;
  kind?: string;
  sizeBytes?: number | null;
  thumbSizeBytes?: number | null;
  width?: number | null;
  height?: number | null;
  durationSec?: number | null;
  capturedAt?: string | null;
  locationName?: string | null;
  lat?: number | null;
  lng?: number | null;
  device?: string | null;
  description?: string | null;
  /** Local uri of a thumbnail to upload alongside the original. */
  thumbUri?: string | null;
}

/** Uploads every file, then inserts all rows in one request. All-or-nothing: on any failure, uploaded files are removed. */
export async function uploadAndCreateMediaMany(items: UploadAndCreateParams[]) {
  const userId = await getCurrentUserId();
  const results = await Promise.allSettled(
    items.flatMap((p) => {
      // Only the storage file name; row ids are generated by Supabase.
      const mediaId = randomUUID();
      return [
        uploadToBucket({
          uri: p.uri,
          userId,
          projectId: p.projectId,
          mediaId,
          mimeType: p.mimeType,
        }),
        p.thumbUri
          ? uploadToBucket({
              uri: p.thumbUri,
              userId,
              projectId: p.projectId,
              mediaId,
              mimeType: "image/jpeg",
              kind: "thumbs",
            })
          : Promise.resolve(null),
      ];
    }),
  );

  const paths = results.map((r) => (r.status === "fulfilled" ? r.value : null));
  const uploaded = paths.filter((v): v is string => v !== null);
  const failed = results.find((r) => r.status === "rejected");
  if (failed) {
    await removeFromBucket(uploaded).catch(() => {});
    throw (failed as PromiseRejectedResult).reason;
  }

  try {
    return await createMediaMany(
      items.map((p, i) => ({
        project_id: p.projectId,
        folder_id: p.folderId ?? null,
        kind: p.kind ?? (p.mimeType.startsWith("video") ? "video" : "photo"),
        storage_path: paths[i * 2] as string,
        thumb_path: paths[i * 2 + 1],
        mime_type: p.mimeType,
        size_bytes: p.sizeBytes ?? null,
        thumb_size_bytes: p.thumbSizeBytes ?? null,
        duration_sec: p.durationSec ?? null,
        width: p.width ?? null,
        height: p.height ?? null,
        captured_at: p.capturedAt ?? null,
        location_name: p.locationName ?? null,
        lat: p.lat ?? null,
        lng: p.lng ?? null,
        device: p.device ?? null,
        description: p.description ?? null,
      })),
    );
  } catch (e) {
    await removeFromBucket(uploaded).catch(() => {});
    throw e;
  }
}

export async function uploadAndCreateMedia(p: UploadAndCreateParams) {
  const [row] = await uploadAndCreateMediaMany([p]);
  return row;
}
